// The first race on a track as the game sets it up (Difficulty.planField,
// aimed at par, so with the aces), the player's slot driven by an NPC that
// laps at `you` × par (0.91: an average player). Returns every car's laps
// and finish.
function firstRace( track, count, seed, you = 0.91 ) {

	const random = rng( seed * 977 );
	const race = makeRace( track );
	const pool = CARS.slice( 1 );
	const field = planField( count, random ).map( ( p ) => {

		const def = pool.splice( Math.floor( random() * pool.length ), 1 )[ 0 ];
		const car = race.addCar( def, stubModel(), { driver: new AIDriver( race.line, { seed: Math.floor( random() * 1e6 ), aggression: p.aggression } ) } );
		car.paceFactor = p.factor;
		return car;

	} );
	const start = startFor( you * track.par, track.ai );
	const player = race.addCar( CARS[ 0 ], stubModel(), { player: true, driver: new AIDriver( race.line, { skill: start.skill, seed: seed + 50 } ) } );
	player.driver.pace = start.pace;

	race.aimField( track.par * FIRST_RACE, false );
	race.setup( 'race', [ ...field, player ], track.laps );
	race.start();

	const input = { x: 0, z: 0, mode: 'car' };
	let guard = 0;
	while ( race.phase !== 'done' && guard ++ < ( track.laps * 90 + 30 ) / STEP ) race.step( input );

	return { race, field, player };

}

// The wall-rider probe: full throttle, and through every corner it leans on
// the outside wall (the walls are frictionless, so only the kerbs cost it).
// A stand-in for a quick human who uses the walls; its line replaces the
// racing line it'd otherwise follow.
class WallRider extends AIDriver {

	constructor( line, options ) {

		super( line, { ...options, skill: 1 } );

	}

	setup( race ) {

		const racing = race.racing;
		const line = this.line = race.line;
		const n = racing.n;

		// Outside of the bend coming up (turnAhead + = the heading grows,
		// toward lateral −), pressed into the wall, eased over a few metres
		const raw = Array.from( { length: n }, ( _, i ) => {

			const turn = line.turnAhead( i * racing.step - 2, 8 );
			return Math.abs( turn ) > 0.25 ? Math.sign( turn ) * 3.4 : 0;

		} );
		racing.use( raw.map( ( _, i ) => {

			let sum = 0;
			for ( let k = - 3; k <= 3; k ++ ) sum += raw[ ( i + k + n ) % n ];
			return sum / 7;

		} ) );

	}

}

// The yardstick for the best NPC (plan_3 phase 1): alone, in the first
// race's field, where its slow laps lose time, and the wall-rider probe
if ( args.includes( '--ace' ) ) {

	const laps = Number( arg( 'laps', 5 ) );
	const seeds = Number( arg( 'seeds', 5 ) );
	const fields = arg( 'fields', '4,8' ).split( ',' ).map( Number );
	const fmt = ( t ) => t.toFixed( 2 );

	for ( const track of tracks ) {

		const runs = [];
		for ( let seed = 7; seed < 7 + seeds; seed ++ ) runs.push( solo( track, { seed, laps } ) );

		const flying = runs.flatMap( ( r ) => r.laps.slice( 1 ) );
		const firsts = runs.map( ( r ) => r.laps[ 0 ] );
		const sorted = flying.slice().sort( ( a, b ) => a - b );
		const spread = ( sorted[ sorted.length - 1 ] - sorted[ 0 ] ) / median( flying );

		console.log( `\n${ track.id }` );
		console.log( `  alone (skill 1, yellow truck, ${ seeds } seeds × ${ laps } laps): flying median ${ fmt( median( flying ) ) }, best ${ fmt( sorted[ 0 ] ) }, worst ${ fmt( sorted[ sorted.length - 1 ] ) } (spread ${ ( spread * 100 ).toFixed( 1 ) }%), lap 1 ${ fmt( median( firsts ) ) }` );
		console.log( `    a wheel on the kerbs ${ ( mean( runs.map( ( r ) => r.kerb ) ) * 100 ).toFixed( 0 ) }% of the time, mean speed ${ mean( runs.map( ( r ) => r.speed ) ).toFixed( 1 ) } m/s, wand ${ runs.reduce( ( a, r ) => a + r.wand, 0 ) }, launches ${ ( runs.reduce( ( a, r ) => a + r.air, 0 ) / runs.reduce( ( a, r ) => a + r.laps.length, 0 ) ).toFixed( 2 ) } a lap` );

		// The same driver in cars the line wasn't searched with
		const others = [ 'kart-oobi', 'tractor-shovel', 'race' ].map( ( id ) => {

			const r = [ 7, 8, 9 ].map( ( seed ) => solo( track, { def: CARS.find( ( c ) => c.id === id ), seed, laps } ) );
			const laps1 = r.flatMap( ( x ) => x.laps.slice( 1 ) );
			return `${ id } ${ laps1.length ? fmt( median( laps1 ) ) : 'DNF' } (wand ${ r.reduce( ( a, x ) => a + x.wand, 0 ) }, launches ${ ( r.reduce( ( a, x ) => a + x.air, 0 ) / Math.max( 1, r.reduce( ( a, x ) => a + x.laps.length, 0 ) ) ).toFixed( 2 ) } a lap)`;

		} );
		console.log( `    other cars: ${ others.join( ', ' ) }` );

		// Slowest lap against best lap, cell by cell, summed over the runs
		const lost = [];

		for ( const r of runs ) {

			const fly = r.laps.slice( 1 );
			if ( fly.length < 2 ) continue;
			const best = r.cellTimes[ 1 + fly.indexOf( Math.min( ...fly ) ) ];
			const worst = r.cellTimes[ 1 + fly.indexOf( Math.max( ...fly ) ) ];
			worst.forEach( ( t, cell ) => lost[ cell ] = ( lost[ cell ] || 0 ) + t - ( best[ cell ] || 0 ) );

		}

		const top = lost.map( ( t, cell ) => [ cell, t / runs.length ] ).filter( ( e ) => e[ 1 ] !== undefined ).sort( ( a, b ) => b[ 1 ] - a[ 1 ] ).slice( 0, 5 );
		const letters = track.layout ? track.layout.replace( / /g, '' ) : null;
		console.log( `    slow laps lose most in cells ${ top.map( ( [ cell, t ] ) => `${ cell }${ letters ? letters[ cell ] : '' } ${ t.toFixed( 2 ) } s` ).join( ', ' ) }` );

		// The first race: the aces start behind the slower NPCs. Their lap 1
		// against the same driver's alone (the calibration's skill and pace
		// for the ace lap)
		const aceAlone = ACES.map( ( f ) => {

			const start = startFor( f * track.ace, track.ai );
			return median( [ 7, 8, 9 ].map( ( seed ) => solo( track, { skill: start.skill, pace: start.pace, seed, laps: 2 } ).laps[ 0 ] ) );

		} );

		for ( const count of fields ) {

			const lap1 = [ [], [] ], total = [ [], [] ], wins = [ 0, 0 ];

			for ( let seed = 1; seed <= seeds; seed ++ ) {

				const { race, field } = firstRace( track, count, seed );
				const aces = field.filter( ( c ) => c.ace ).sort( ( a, b ) => a.targetLap - b.targetLap );
				const winner = race.standings()[ 0 ];

				aces.forEach( ( c, i ) => {

					if ( c.lapTimes.length ) lap1[ i ].push( c.lapTimes[ 0 ] );
					if ( c.finished ) total[ i ].push( c.finishTime );
					if ( c === winner ) wins[ i ] ++;

				} );

			}

			const ace = ( i ) => `lap 1 ${ lap1[ i ].length ? fmt( median( lap1[ i ] ) ) : '-' } (+${ lap1[ i ].length ? fmt( median( lap1[ i ] ) - aceAlone[ i ] ) : '-' } on alone), race ${ total[ i ].length ? fmt( median( total[ i ] ) ) : '-' }, wins ${ wins[ i ] }`;
			console.log( `  first race, ${ count } NPCs + an average bot (aces at ${ fmt( track.ace ) } and ${ fmt( track.ace * 1.05 ) }): ace ${ ace( 0 ) }; second ace ${ ace( 1 ) }` );

		}

		// The wall-rider probe
		const riders = [];
		for ( let seed = 7; seed < 7 + Math.min( 3, seeds ); seed ++ ) riders.push( solo( track, { seed, laps, driver: new WallRider( null, { seed } ) } ) );
		const riderLaps = riders.flatMap( ( r ) => r.laps.slice( 1 ) );
		console.log( `  wall-rider probe: flying median ${ riderLaps.length ? fmt( median( riderLaps ) ) : 'DNF' }, best ${ riderLaps.length ? fmt( Math.min( ...riderLaps ) ) : '-' }, kerbs ${ ( mean( riders.map( ( r ) => r.kerb ) ) * 100 ).toFixed( 0 ) }%, wand ${ riders.reduce( ( a, r ) => a + r.wand, 0 ) }` );

	}

}

// Steering gains (AIDriver.STEER) for the best NPC: every combination of
// the values given (--gain 2,3 --lead 0.3,0.5 …), scored on each track by
// its median flying lap against the track's skill-1 lap in Tracks.js, plus
// the spread between its laps and any wand carries
if ( args.includes( '--steer' ) ) {

	const keys = Object.keys( STEER );
	const values = keys.map( ( key ) => arg( key, String( STEER[ key ] ) ).split( ',' ).map( Number ) );
	const sets = [ {} ];
	keys.forEach( ( key, k ) => sets.splice( 0, sets.length, ...sets.flatMap( ( set ) => values[ k ].map( ( value ) => ( { ...set, [ key ]: value } ) ) ) ) );

	const seeds = Number( arg( 'seeds', 3 ) );
	const laps = Number( arg( 'laps', 4 ) );
	const cars = arg( 'cars', 'vehicle-truck-yellow' ).split( ',' );
	const pool = new Pool();
	const results = [];

	console.log( `${ sets.length } steering sets × ${ tracks.length } tracks × ${ cars.length } cars × ${ seeds } seeds\n` );

	await Promise.all( sets.map( async ( steer ) => {

		const scores = await Promise.all( tracks.map( async ( track ) => {

			const runs = await pool.all( cars.flatMap( ( car ) => Array.from( { length: seeds }, ( _, i ) => ( { track: track.id, car, seed: 7 + i, laps, steer } ) ) ) );
			const flying = runs.flatMap( ( r ) => r.laps.slice( 1 ) );
			const wand = runs.reduce( ( a, r ) => a + r.wand, 0 );
			if ( flying.length < runs.length ) return { lap: Infinity, score: 3 };
			const lap = median( flying );
			const spread = ( Math.max( ...flying ) - Math.min( ...flying ) ) / lap;
			return { lap, spread, wand, score: lap / track.ai[ track.ai.length - 1 ] + 0.5 * spread + 0.03 * wand };

		} ) );

		const score = mean( scores.map( ( s ) => s.score ) );
		results.push( { steer, score, scores } );
		console.log( `${ score.toFixed( 4 ) }  ${ JSON.stringify( steer ) }  ${ scores.map( ( s, i ) => `${ tracks[ i ].id } ${ Number.isFinite( s.lap ) ? s.lap.toFixed( 2 ) + ' ±' + ( s.spread * 50 ).toFixed( 1 ) + '%' + ( s.wand ? ' w' + s.wand : '' ) : 'DNF' }` ).join( ', ' ) }` );

	} ) );

	pool.close();
	results.sort( ( a, b ) => a.score - b.score );
	console.log( '\nBest:' );
	for ( const r of results.slice( 0, 5 ) ) console.log( `  ${ r.score.toFixed( 4 ) }  ${ JSON.stringify( r.steer ) }` );

}

// The fastest line per track (plan_3 phase 3): a (1+λ) evolution strategy
// on the line's offsets at its control points (RacingLine.CONTROL m apart)
// and speed caps there, starting from the saved line (--fresh: the better
// of the smooth line and the centerline). Each candidate drives a truck and
// a kart over --seeds seeds with a little steering wobble, so the line
// holds up off its exact path; it's scored on the mean flying lap, plus
// the spread between laps and any wand carries. Writes js/RaceLines.js
// after each track.
if ( args.includes( '--optimize' ) ) {

	const budget = Number( arg( 'candidates', 2000 ) );
	const lambda = Number( arg( 'lambda', 16 ) );
	const seeds = Number( arg( 'seeds', 2 ) );
	const cars = arg( 'cars', 'vehicle-truck-yellow,kart-oobi' ).split( ',' );
	const noise = Number( arg( 'noise', 0.03 ) );
	const laps = 4;
	const random = rng( Number( arg( 'seed', 1 ) ) );
	const gauss = () => Math.sqrt( - 2 * Math.log( 1 - random() ) ) * Math.cos( 2 * Math.PI * random() );
	const pool = new Pool();
	const saved = { ...RACE_LINES };

	for ( const track of tracks ) {

		const racing = makeRace( track ).racing;
		const k = racing.controls;
		const index = ( j ) => Math.round( j * racing.n / k ) % racing.n;
		const lo = Array.from( { length: k }, ( _, j ) => racing.lo[ index( j ) ] );
		const hi = Array.from( { length: k }, ( _, j ) => racing.hi[ index( j ) ] );

		const evaluate = async ( line ) => {

			const runs = await pool.all( cars.flatMap( ( car ) => Array.from( { length: seeds }, ( _, i ) => ( { track: track.id, car, seed: 1 + i, laps, noise, line } ) ) ) );
			if ( runs.some( ( r ) => r.laps.length < laps ) ) return { score: Infinity };
			const flying = runs.map( ( r ) => r.laps.slice( 1 ) );
			const lap = mean( flying.flat() );
			const spread = mean( flying.map( ( l ) => Math.max( ...l ) - Math.min( ...l ) ) );
			const wand = mean( runs.map( ( r ) => r.wand ) );
			return { score: lap + 0.5 * spread + 3 * wand, lap, spread, wand, kerb: mean( runs.map( ( r ) => r.kerb ) ) };

		};

		const candidate = ( offsets, caps = null ) => ( { offsets: offsets.map( ( o, j ) => Math.max( lo[ j ], Math.min( hi[ j ], o ) ) ), caps: caps || new Array( k ).fill( 0 ) } );
		const sample = ( offsets ) => Array.from( { length: k }, ( _, j ) => offsets[ index( j ) ] );
		const starts = [ candidate( sample( racing.smoothLine() ) ), candidate( new Array( k ).fill( 0 ) ) ];
		if ( racing.optimized && ! args.includes( '--fresh' ) ) starts.unshift( candidate( saved[ track.id ].offsets.map( ( o ) => o / 100 ), saved[ track.id ].caps ) );

		let parent = null, best = { score: Infinity };

		for ( const start of starts ) {

			const result = await evaluate( start );
			console.log( `${ track.id }: start ${ starts.indexOf( start ) } lap ${ result.lap?.toFixed( 3 ) } score ${ result.score.toFixed( 3 ) }` );
			if ( result.score < best.score ) [ parent, best ] = [ start, result ];

		}

		const first = best;
		let sigma = 0.5;
		const t0 = performance.now();

		for ( let generation = 0; generation * lambda < budget; generation ++ ) {

			const children = Array.from( { length: lambda }, () => {

				const child = { offsets: parent.offsets.slice(), caps: parent.caps.slice() };
				const r = random();

				if ( r < 0.75 ) {

					// A bump over a few control points
					const c = Math.floor( random() * k ), w = 1 + Math.floor( random() * 5 ), a = gauss() * sigma;
					for ( let d = - w; d <= w; d ++ ) child.offsets[ ( c + d + k ) % k ] += a * 0.5 * ( 1 + Math.cos( Math.PI * d / ( w + 1 ) ) );

				} else if ( r < 0.9 ) {

					for ( let j = 0; j < k; j ++ ) child.offsets[ j ] += gauss() * sigma * 0.3;

				} else {

					// A speed cap: set, moved or lifted
					const c = Math.floor( random() * k );
					if ( child.caps[ c ] && random() < 0.4 ) child.caps[ c ] = 0;
					else child.caps[ c ] = Math.round( 10 * Math.max( 6, Math.min( DRIVE.top, ( child.caps[ c ] || 13 ) + gauss() * 1.5 ) ) ) / 10;

				}

				return candidate( child.offsets, child.caps );

			} );

			const results = await Promise.all( children.map( evaluate ) );
			const i = results.reduce( ( a, r, j ) => r.score < results[ a ].score ? j : a, 0 );

			if ( results[ i ].score < best.score ) {

				[ parent, best ] = [ children[ i ], results[ i ] ];
				sigma = Math.min( 1.5, sigma * 1.15 );

			} else {

				// Shrinking steps; stuck at the smallest, start wide again
				sigma = sigma < 0.05 ? 0.5 : sigma * 0.93;

			}

			if ( generation % 10 === 9 ) console.log( `  ${ ( generation + 1 ) * lambda } candidates, ${ ( ( performance.now() - t0 ) / 1000 ).toFixed( 0 ) } s: lap ${ best.lap.toFixed( 3 ) } (from ${ first.lap.toFixed( 3 ) }), spread ${ best.spread.toFixed( 3 ) }, wand ${ best.wand.toFixed( 2 ) }, kerbs ${ ( best.kerb * 100 ).toFixed( 0 ) }%, σ ${ sigma.toFixed( 2 ) }, caps ${ parent.caps.filter( Boolean ).length }` );

		}

		saved[ track.id ] = { hash: lineHash( track ), offsets: parent.offsets.map( ( o ) => Math.round( o * 100 ) ), caps: parent.caps };
		writeFileSync( new URL( '../../js/RaceLines.js', import.meta.url ), RACE_LINES_HEADER + 'export const RACE_LINES = {\n' + Object.entries( saved ).map( ( [ id, l ] ) => `\t${ id }: {\n\t\thash: '${ l.hash }',\n\t\toffsets: [ ${ l.offsets.join( ', ' ) } ],\n\t\tcaps: [ ${ l.caps.join( ', ' ) } ],\n\t},\n` ).join( '' ) + '};\n' );
		console.log( `${ track.id }: lap ${ first.lap.toFixed( 3 ) } → ${ best.lap.toFixed( 3 ) } (${ ( ( best.lap / first.lap - 1 ) * 100 ).toFixed( 1 ) }%), saved` );

	}

	pool.close();

}

