	results.sort( ( a, b ) => a.score - b.score );
	console.log( '\nBest:', results.slice( 0, 5 ).map( ( r ) => `grip ${ r.grip } brake ${ r.brake } yaw ${ r.yaw } (${ ( ( r.score - 1 ) * 100 ).toFixed( 1 ) }% off the best per track)` ).join( '; ' ) );

