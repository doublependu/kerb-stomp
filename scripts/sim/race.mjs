// Headless races: the game's own simulation (js/Race.js) and NPC drivers,
// with no rendering, faster than real time.
//
//   npm run sim -- --calibrate                 lap time per AI skill, per track
//   npm run sim -- --soak                      9 cars × 20 laps × every track × 3 seeds
//   npm run sim -- --soak --tracks monza --laps 5 --seeds 1
//   npm run sim -- --balance                   stand-in players (by share of par) race the field twice, as in the game
//   npm run sim -- --fit                       grip and braking for the NPCs' speed profile (RacingLine.DRIVE)
//   npm run sim -- --ace                       the best NPC: alone, in the first race's field, and a wall-riding probe
//   npm run sim -- --steer --gain 2,3          steering gains for the best NPC (AIDriver.STEER), over a grid
//   npm run sim -- --optimize --tracks monza   the fastest racing line per track (writes js/RaceLines.js)

